# --- Legacy Link Config (Link1: Sensor -> Gateway) ---
# Must match legacy_device.py PSK - 16B = 128-bit, stored in Flash ROM on real device
PRE_SHARED_KEY = b"legacy_secret_16"
LISTEN_HOST = "127.0.0.1"
LISTEN_PORT = 5000  # Legacy devices connect here via raw TCP

# --- Cloud Forwarding Config (Link2: Gateway -> Cloud PQC) ---
# Where does CLOUD_HOST/CLOUD_PORT come from?
# - Cloud service listens on 6000 for PQC packets (ct+nonce+aes_ct)
# - Gateway forwards after validating legacy payload
# - For local run: 127.0.0.1:6000
# - For Docker: gateway container connects to cloud container via Docker network
#   - In docker-compose, cloud service is named "cloud", so gateway can connect to "cloud:6000"
#   - We use env vars to allow override: CLOUD_HOST env var, default 127.0.0.1 for local
#   - For Docker, set CLOUD_HOST=cloud in compose file
CLOUD_HOST = os.getenv("CLOUD_HOST", "127.0.0.1")
CLOUD_PORT = int(os.getenv("CLOUD_PORT", "6000"))

# Where does cloud_public_key.bin come from?
# - Generated by cloud_service.py on startup via generate_keypair() -> writes file
# - For local: ./cloud_public_key.bin in current dir, created when cloud starts
# - For Docker: shared volume /app/shared/cloud_public_key.bin, set via CLOUD_PK_PATH env var
# - Gateway tries to load this file; if missing -> fallback to local log (business continuity)
# - File is gitignored (*.bin) and created at runtime, not committed

# Where does gateway_fallback.log come from?
# - Created by forward_to_cloud() when pk missing or cloud unreachable
# - Format: "<timestamp> <json>" per line, e.g., "1791603565 {"device_id":...}"
# - This is store-and-forward fallback for business continuity (per migration strategy)
# - File is gitignored (*.log) and created at runtime
# - In Docker: can be bind mounted or in shared volume for persistence
FALLBACK_LOG = Path(os.getenv("FALLBACK_LOG", "gateway_fallback.log"))

# --- Health Config ---
HEALTH_HOST = "127.0.0.1"
HEALTH_PORT = 5001  # Health/metrics endpoint, returns JSON with counters

# --- Validation Config ---
# Required telemetry fields - gateway rejects payloads missing these (schema validation)
# This is part of hardening to pass tests: test_gateway_rejects_wrong_telemetry_schema
REQUIRED_FIELDS = {"device_id", "timestamp", "temperature", "humidity", "status"}

# --- Replay Protection (simple, in-memory) ---
# In-memory set of seen nonces (12B each) - simple for 4h scope
# How it works: after successful decrypt+validation, add nonce to set; if nonce already in set, reject as replay
# Tech debt: no TTL, grows forever, cleared on restart -> could OOM or allow replay after restart
# Future: LRU cache with TTL (e.g., 5 min) or timestamp window
seen_nonces: set[bytes] = set()

# --- Metrics for Observability (in-memory counters, thread-safe) ---
# These are simple analytics for gateway side observability
# Exposed via health endpoint 5001 /health -> JSON
# For cloud side analytics, see cloud_service.py which has SQLite + avg temp etc.
metrics = {
    "received": 0,  # Valid telemetry received from legacy
    "rejected": 0,  # Total rejected (malformed, invalid json, invalid schema, replay)
    "replayed": 0,  # Replay detected (nonce already seen)
    "invalid_json": 0,  # JSON parse failed
    "invalid_schema": 0,  # Schema validation failed (missing required fields)
    "empty": 0,  # Empty connections (EOF before any bytes)
    "forwarded_to_cloud": 0,  # Successfully forwarded to cloud via PQC
    "fallback_local": 0,  # Stored to fallback log (pk missing or cloud down)
    "cloud_fail": 0,  # Cloud unreachable (connection refused, timeout)
    "uptime_start": time.time(),  # For uptime calculation
}

# Thread lock for metrics (health server runs in separate thread, main loop updates metrics)
metrics_lock = threading.Lock()

# --- Logging: file only to keep stdout clean for tests ---
# Why file only? Tests in conftest.py use GatewayProcess which does:
#   subprocess.Popen(..., stdout=PIPE, stderr=STDOUT, text=True)
# It merges stdout+stderr and reads line-by-line via queue.Queue, wait_for_line looks for "Received from device:"
# If we log to stderr (default), logs go into same pipe as stdout and cause:
#   "Received from device: {...}2026-10-10 INFO Gateway health listening..." concatenated -> test failure
# So we log to file only (gateway.log, gitignored via *.log) to keep stdout clean (only "Edge Gateway listening..." and "Received..." prints)
# For real ops, you would add StreamHandler to stderr and RotatingFileHandler
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
    handlers=[
        logging.FileHandler("gateway.log"),
    ],
)


def decrypt_payload(encrypted_packet: bytes, key: bytes) -> str:
    """
    Extracts nonce, verifies authenticity, and decrypts payload (Link1 AES-GCM)
    - Slices first 12B as nonce, rest as ciphertext+tag
    - AESGCM decrypt checks GMAC tag first, raises InvalidTag if tampered or wrong key
    - Returns UTF-8 JSON string
    """
    nonce = encrypted_packet[:12]
    ciphertext = encrypted_packet[12:]
    aesgcm = AESGCM(key)
    decrypted_bytes = aesgcm.decrypt(nonce, ciphertext, None)
    return decrypted_bytes.decode("utf-8")


def validate_telemetry_schema(payload: dict) -> bool:
    """Check that payload contains all required telemetry fields (schema validation)"""
    if not isinstance(payload, dict):
        return False
    return REQUIRED_FIELDS.issubset(payload.keys())


def forward_to_cloud(telemetry_json_str: str) -> bool:
    """
    Forward telemetry to cloud via PQC hybrid encryption (Link2)
    Returns True if forwarded, False if fallback to local log
    Steps:
    1. Try load public key file (cloud_public_key.bin) - file-based distribution Phase1
       - Where does file come from? Generated by cloud on startup, shared via volume in Docker
       - If missing -> fallback (business continuity)
    2. Encrypt via pqc_utils.encrypt_for_cloud: ML-KEM encaps -> ss 32B, ct 768B + AES-GCM encrypt with ss
       - Wire format: ct(768)||nonce(12)||aes_ct
       - Metrics: encaps_ms, total_len logged for PQC observability
    3. Send via TCP to cloud:6000 with EOF framing (sendall + shutdown WR)
       - If cloud unreachable (ConnectionRefused, timeout) -> fallback
    4. Fallback: append "<timestamp> <json>" to gateway_fallback.log, increment fallback_local metric
    """
    try:
        # Try load public key (file-based distribution - Phase1 simple)
        # For local: ./cloud_public_key.bin, for Docker: /app/shared/cloud_public_key.bin via env var
        try:
            ek_bytes = load_public_key(CLOUD_PK_PATH)
        except (FileNotFoundError, ValueError) as e:
            # Fallback: pk not available, store locally (business continuity)
            logging.warning(f"Cloud public key not available ({e}), using fallback log")
            with metrics_lock:
                metrics["fallback_local"] += 1
            # Append to fallback log with timestamp
            with open(FALLBACK_LOG, "a") as f:
                f.write(f"{int(time.time())} {telemetry_json_str}\n")
            logging.info(f"Fallback stored to {FALLBACK_LOG}")
            return False

        # Encrypt for cloud via PQC hybrid
        plaintext = telemetry_json_str.encode("utf-8")
        packet, pqc_metrics = encrypt_for_cloud(plaintext, ek_bytes)

        # Send to cloud via TCP 6000 (data plane)
        # For local: 127.0.0.1:6000, for Docker: cloud:6000 via env CLOUD_HOST=cloud
        try:
            with socket.create_connection((CLOUD_HOST, CLOUD_PORT), timeout=3) as sock:
                sock.sendall(packet)
                sock.shutdown(socket.SHUT_WR)  # EOF framing
            with metrics_lock:
                metrics["forwarded_to_cloud"] += 1
            logging.info(
                f"Forwarded to cloud {CLOUD_HOST}:{CLOUD_PORT}, PQC {pqc_metrics['encaps_ms']}ms, {pqc_metrics['total_len']}B"
            )
            return True
        except (ConnectionRefusedError, OSError, socket.timeout) as e:
            # Fallback: cloud unreachable, store locally
            logging.warning(f"Cloud unreachable ({e}), fallback to local log")
            with metrics_lock:
                metrics["cloud_fail"] += 1
                metrics["fallback_local"] += 1
            with open(FALLBACK_LOG, "a") as f:
                f.write(f"{int(time.time())} {telemetry_json_str}\n")
            return False

    except Exception as e:
        # Unexpected error, still fallback to avoid data loss
        logging.error(f"Unexpected error in forward_to_cloud: {e}", exc_info=True)
        with metrics_lock:
            metrics["fallback_local"] += 1
        try:
            with open(FALLBACK_LOG, "a") as f:
                f.write(f"{int(time.time())} {telemetry_json_str}\n")
        except Exception:
            pass
        return False


class HealthHandler(BaseHTTPRequestHandler):
    """Health/metrics HTTP handler for gateway (port 5001)"""

    def do_GET(self):
        # Handle /health, /metrics, / endpoints - return JSON metrics
        if self.path in ["/health", "/metrics", "/"]:
            with metrics_lock:
                uptime = time.time() - metrics["uptime_start"]
                data = {
                    "status": "ok",
                    "service": "edge_gateway",
                    "metrics": {
                        "received": metrics["received"],
                        "rejected": metrics["rejected"],
                        "replayed": metrics["replayed"],
                        "invalid_json": metrics["invalid_json"],
                        "invalid_schema": metrics["invalid_schema"],
                        "empty": metrics["empty"],
                        "forwarded_to_cloud": metrics["forwarded_to_cloud"],
                        "fallback_local": metrics["fallback_local"],
                        "cloud_fail": metrics["cloud_fail"],
                    },
                    "replay_cache_size": len(seen_nonces),
                    "uptime_s": round(uptime, 1),
                }
            self.send_response(200)
            self.send_header("Content-type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps(data, indent=2).encode())
        else:
            self.send_response(404)
            self.end_headers()
            self.wfile.write(b'{"status":"not found"}')

    def log_message(self, format, *args):
        # Log health requests to file (not stdout) to keep tests clean
        logging.info(f"Health request {self.client_address} {format % args}")


def start_health_server():
    """Start health server on 5001 in background daemon thread"""
    try:
        server = HTTPServer((HEALTH_HOST, HEALTH_PORT), HealthHandler)
        logging.info(f"Gateway health listening on {HEALTH_HOST}:{HEALTH_PORT}")
        # Do not print to stdout to keep tests clean (only log to file)
        # Tests only expect "Edge Gateway listening..." and "Received..." on stdout
        server.serve_forever()
    except Exception as e:
        logging.error(f"Health server failed: {e}", exc_info=True)


def start_gateway():
    """Main gateway loop - handles legacy devices on 5000, forwards to cloud, health on 5001"""
    # Start health server in background thread (daemon, so it dies when main thread dies)
    health_thread = threading.Thread(target=start_health_server, daemon=True)
    health_thread.start()

    # Set up TCP server socket for legacy devices (Link1)
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as server:
        server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        server.bind((LISTEN_HOST, LISTEN_PORT))
        server.listen()
        # This print is expected by tests (wait_for_line "Edge Gateway listening...")
        print(f"Edge Gateway listening for legacy devices on port {LISTEN_PORT}...")
        logging.info(f"Gateway listening on {LISTEN_HOST}:{LISTEN_PORT}")

        while True:
            # Block until legacy device connects
            try:
                conn, addr = server.accept()
            except Exception as e:
                logging.error(f"Accept failed: {e}", exc_info=True)
                continue

            with conn:
                buffer = bytearray()
                try:
                    while True:
                        # Read incoming chunks (TCP stream, no message boundaries, so accumulate until EOF)
                        chunk = conn.recv(1024)
                        if not chunk:
                            # Empty bytes = client closed connection (EOF framing)
                            break
                        buffer.extend(chunk)
                except Exception as e:
                    logging.warning(f"Recv error from {addr}: {e}")
                    with metrics_lock:
                        metrics["rejected"] += 1
                    continue

                # Handle empty connection (client connected and immediately closed)
                if not buffer:
                    logging.info(f"Empty connection from {addr}, ignoring")
                    with metrics_lock:
                        metrics["empty"] += 1
                    continue

                # Minimum length check: need at least 12B nonce + 1B ciphertext + 16B tag = 29B, but we check 13B minimal to catch truncated early
                if len(buffer) < 13:
                    logging.warning(
                        f"Rejected packet too short ({len(buffer)} bytes) from {addr}"
                    )
                    with metrics_lock:
                        metrics["rejected"] += 1
                    continue

                try:
                    # Extract nonce (first 12B) for replay check
                    nonce = bytes(buffer[:12])

                    # Replay protection: if nonce already seen, reject (security)
                    # Note: we add nonce to seen set only AFTER successful validation (see below)
                    # So truncated or invalid packets don't add nonce, allowing valid packet with same nonce to still pass
                    # For replay test: first valid packet adds nonce, second same nonce is rejected as replay
                    if nonce in seen_nonces:
                        logging.warning(
                            f"Replay detected nonce={nonce.hex()} from {addr}, rejecting"
                        )
                        with metrics_lock:
                            metrics["replayed"] += 1
                            metrics["rejected"] += 1
                        continue

                    # Decrypt Link1 AES-GCM
                    raw_data = decrypt_payload(bytes(buffer), PRE_SHARED_KEY)

                    # Validate JSON (application layer)
                    try:
                        payload = json.loads(raw_data)
                    except json.JSONDecodeError as e:
                        logging.warning(
                            f"Invalid JSON from {addr}: {e}, data={raw_data[:100]!r}"
                        )
                        with metrics_lock:
                            metrics["invalid_json"] += 1
                            metrics["rejected"] += 1
                        continue

                    # Validate schema (required fields)
                    if not validate_telemetry_schema(payload):
                        logging.warning(
                            f"Invalid schema from {addr}: missing {REQUIRED_FIELDS - set(payload.keys()) if isinstance(payload, dict) else 'not dict'} payload={payload}"
                        )
                        with metrics_lock:
                            metrics["invalid_schema"] += 1
                            metrics["rejected"] += 1
                        continue

                    # All checks passed -> add nonce to seen set (replay protection) and process
                    seen_nonces.add(nonce)
                    with metrics_lock:
                        metrics["received"] += 1
                    # This print is expected by tests (wait_for_line "Received from device:")
                    print(f"Received from device: {raw_data}")
                    logging.info(
                        f"Valid telemetry from {payload.get('device_id')} temp={payload.get('temperature')} addr={addr}"
                    )

                    # Forward to cloud via PQC (Link2) with fallback to local log
                    forward_to_cloud(raw_data)

                except (InvalidTag, ValueError, UnicodeDecodeError) as e:
                    # Malformed packet: wrong key, tampered, truncated, etc. -> reject but keep gateway alive
                    logging.warning(
                        f"Rejected malformed packet from {addr}: {type(e).__name__}: {e}"
                    )
                    with metrics_lock:
                        metrics["rejected"] += 1
                    continue
                except Exception as e:
                    # Unexpected error -> log and continue (don't crash gateway)
                    logging.error(
                        f"Unexpected error processing packet from {addr}: {e}",
                        exc_info=True,
                    )
                    with metrics_lock:
                        metrics["rejected"] += 1
                    continue


if __name__ == "__main__":
    start_gateway()
