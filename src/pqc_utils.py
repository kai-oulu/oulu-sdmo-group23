"""
PQC Utilities for ML-KEM-512 hybrid encryption (Link 2: Gateway -> Cloud)
- Uses mlkem library (Rust binding) with NIST FIPS 203 ML-KEM-512
- Hybrid pattern: ML-KEM encaps -> 32B shared secret -> AES-256-GCM encrypt telemetry
- Wire format: ct(768) || nonce(12) || aes_ciphertext+tag
- Simple DB and observability handled in cloud_service.py
"""

import logging
import os
import time
from pathlib import Path
from typing import Tuple

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from mlkem import ML_KEM, ParameterSet

# --- Constants for ML-KEM-512 (lightest, suitable for gateway) ---
# ML-KEM-512 is chosen because it has smallest overhead (800B pk, 768B ct) vs 768 (1184B pk) and 1024 (1568B pk)
# Security: ~AES-128 equivalent (Category 1), sufficient for short-lived telemetry (not decades)
PK_LEN = 800  # Encaps key (public) length - 800 bytes for ML-KEM-512
SK_LEN = 1632  # Decaps key (secret) length - 1632 bytes, stays in memory in cloud (never written to file for simplicity)
CT_LEN = 768  # Ciphertext length - 768 bytes encapsulation ciphertext
SS_LEN = 32  # Shared secret length - 32 bytes, used as AES-256-GCM key (32B = 256-bit)
NONCE_LEN = 12  # AES-GCM nonce length - 12 bytes (96-bit) random per message, must never reuse with same key

# --- Public key path handling for Docker and local ---
# Where does cloud_public_key.bin come from?
# - Generated by cloud_service.py on startup via generate_keypair() -> writes to this path inside container/host
# - For local run: file created in current dir (./cloud_public_key.bin) when cloud starts
# - For Docker: we want shared volume so gateway can read same file
#   - Option A (old): bind mount ./cloud_public_key.bin:/app/cloud_public_key.bin - fragile if host file doesn't exist (Docker creates directory)
#   - Option B (new, recommended): use env var CLOUD_PK_PATH to point to shared volume /app/shared/cloud_public_key.bin
#   - We support both: env var overrides default, so Docker can set CLOUD_PK_PATH=/app/shared/cloud_public_key.bin
#   - Fallback: if env var not set, use default ./cloud_public_key.bin (local dev)
#   - This file is gitignored (*.bin) and created at runtime, not committed
CLOUD_PK_PATH = Path(os.getenv("CLOUD_PK_PATH", "cloud_public_key.bin"))

# --- Logging: file only to keep stdout clean for tests ---
# Why file only? Tests in conftest.py merge stdout+stderr (stderr=STDOUT) and wait_for_line looks for "Received from device:"
# If we log to stderr, logs pollute stdout pipe and cause "Received ...2026-10-10 INFO..." concatenated line -> test failure
# So we log to pqc.log file only (gitignored via *.log)
# For real ops, you would also add StreamHandler to stderr or use RotatingFileHandler
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
    handlers=[
        logging.FileHandler("pqc.log"),
    ],
)


def get_mlkem_instance():
    """Get ML-KEM-512 instance - this is the NIST FIPS 203 standard object"""
    # ML_KEM is from mlkem Rust binding, ParameterSet.ML_KEM_512 is Category 1
    return ML_KEM(ParameterSet.ML_KEM_512)


def generate_keypair(
    save_path: Path = CLOUD_PK_PATH,
) -> Tuple[bytes, bytes, ML_KEM]:
    """
    Generate ML-KEM-512 keypair and save public key to file.
    Returns (ek_bytes, dk_bytes, mlkem_obj)
    ek = encaps key (public, 800B) - shared with gateway via file
    dk = decaps key (secret, 1632B) - stays in memory in cloud, never written (simple)
    save_path: where to save public key file - default from env var or ./cloud_public_key.bin
               In Docker, set env CLOUD_PK_PATH=/app/shared/cloud_public_key.bin and mount shared volume
    """
    mlkem_obj = get_mlkem_instance()
    # key_gen() returns (EncapsKey, DecapsKey) - note order is (public, private)
    ek, dk = mlkem_obj.key_gen()  # ek is EncapsKey (public), dk is DecapsKey (secret)
    ek_bytes = ek.to_bytes()
    dk_bytes = dk.to_bytes()

    # Validate lengths match expected for ML-KEM-512
    assert len(ek_bytes) == PK_LEN, f"Unexpected pk len {len(ek_bytes)}"
    assert len(dk_bytes) == SK_LEN, f"Unexpected sk len {len(dk_bytes)}"

    # Save public key for gateway to read (file-based distribution - Phase1 simple)
    # In local run: writes to ./cloud_public_key.bin in current dir
    # In Docker: writes to /app/shared/cloud_public_key.bin if env var set, shared via volume pqc-shared
    # This file is created at runtime, not committed (gitignored *.bin)
    save_path.parent.mkdir(parents=True, exist_ok=True)  # Ensure directory exists (for shared/ case)
    save_path.write_bytes(ek_bytes)
    logging.info(
        f"Generated ML-KEM-512 keypair: pk {len(ek_bytes)}B saved to {save_path}, sk {len(dk_bytes)}B in memory (not saved)"
    )
    return ek_bytes, dk_bytes, mlkem_obj


def load_public_key(path: Path = CLOUD_PK_PATH) -> bytes:
    """
    Load public key from file - used by gateway to encrypt for cloud
    Tries multiple locations for Docker compatibility:
    - First try exact path from env var (e.g., /app/shared/cloud_public_key.bin)
    - Then try default ./cloud_public_key.bin
    - Then try shared/cloud_public_key.bin (common Docker shared volume)
    """
    # Try primary path
    if path.exists():
        data = path.read_bytes()
        if len(data) != PK_LEN:
            raise ValueError(f"Invalid pk length {len(data)}, expected {PK_LEN}")
        return data

    # Try fallback locations for Docker compatibility
    fallback_paths = [
        Path("cloud_public_key.bin"),
        Path("shared/cloud_public_key.bin"),
        Path("/app/shared/cloud_public_key.bin"),
        Path("./shared/cloud_public_key.bin"),
    ]
    for fp in fallback_paths:
        if fp.exists() and fp != path:
            logging.info(f"Public key not at {path}, found at fallback {fp}")
            data = fp.read_bytes()
            if len(data) == PK_LEN:
                return data

    raise FileNotFoundError(f"Public key file not found: {path} (tried fallbacks {fallback_paths})")


def encrypt_for_cloud(plaintext: bytes, ek_bytes: bytes) -> Tuple[bytes, dict]:
    """
    Hybrid encrypt: ML-KEM encaps + AES-256-GCM
    Used by gateway to forward telemetry to cloud
    Returns (packet, metrics)
    packet = ct(768) || nonce(12) || aes_ct+tag (variable, ~65B for small JSON, total ~845B)
    metrics = {encaps_ms, aes_encrypt_ms, total_ms, ct_len, total_len} for PQC observability
    """
    start = time.time()

    # Load ek from bytes and encaps - need to handle different mlkem versions
    from mlkem import EncapsKey

    mlkem_obj = get_mlkem_instance()
    # EncapsKey.from_bytes signature differs by version: some need param set, some not
    try:
        ek = EncapsKey.from_bytes(ek_bytes)
    except TypeError:
        # Fallback for versions requiring param set
        ek = EncapsKey.from_bytes(ek_bytes, ParameterSet.ML_KEM_512)

    # Encapsulate: generates random shared secret (32B) and ciphertext (768B)
    # This is the PQC part - quantum-resistant key establishment
    encaps_start = time.time()
    ss, ct = mlkem_obj.encaps(ek)  # ss = shared secret 32B, ct = ciphertext 768B
    encaps_ms = (time.time() - encaps_start) * 1000

    assert len(ss) == SS_LEN
    assert len(ct) == CT_LEN

    # AES-256-GCM encrypt plaintext with ss as key (hybrid encryption)
    # Why AES-256? ss is 32B = 256-bit, so AES-256-GCM
    # Nonce 12B random per message, must never reuse with same ss (ss is fresh per encaps, so ok)
    aes_start = time.time()
    nonce = os.urandom(NONCE_LEN)
    aesgcm = AESGCM(ss)  # ss is 32B -> AES-256
    aes_ct = aesgcm.encrypt(nonce, plaintext, None)  # No associated data, tag appended automatically
    aes_ms = (time.time() - aes_start) * 1000

    # Wire format: ct || nonce || aes_ct (ct 768, nonce 12, aes_ct variable)
    packet = ct + nonce + aes_ct

    total_ms = (time.time() - start) * 1000
    metrics = {
        "encaps_ms": round(encaps_ms, 2),
        "aes_encrypt_ms": round(aes_ms, 2),
        "total_ms": round(total_ms, 2),
        "ct_len": len(ct),
        "nonce_len": len(nonce),
        "aes_ct_len": len(aes_ct),
        "total_len": len(packet),
        "ss_len": len(ss),
    }

    # PQC observability: log encaps time and sizes
    logging.info(
        f"PQC encrypt: encaps {metrics['encaps_ms']}ms, AES {metrics['aes_encrypt_ms']}ms, total {len(packet)}B (ct 768 + nonce 12 + aes {len(aes_ct)})"
    )

    return packet, metrics


def decrypt_from_gateway(
    packet: bytes, dk_bytes: bytes, mlkem_obj: ML_KEM = None
) -> Tuple[bytes, dict]:
    """
    Hybrid decrypt: split packet, decaps ct -> ss, AES-GCM decrypt
    Used by cloud to receive from gateway
    Returns (plaintext, metrics)
    metrics = {decaps_ms, aes_decrypt_ms, total_ms} for PQC observability
    """
    start = time.time()

    # Validate minimum length: ct 768 + nonce 12 + tag 16 = 796B min
    if len(packet) < CT_LEN + NONCE_LEN + 16:  # 16 is min GCM tag
        raise ValueError(f"Packet too short {len(packet)}, expected at least {CT_LEN+NONCE_LEN+16}")

    # Split packet: ct (768) || nonce (12) || aes_ct (rest)
    ct = packet[:CT_LEN]
    nonce = packet[CT_LEN : CT_LEN + NONCE_LEN]
    aes_ct = packet[CT_LEN + NONCE_LEN :]

    # Decapsulate: recover shared secret from ct using secret key
    from mlkem import DecapsKey

    if mlkem_obj is None:
        mlkem_obj = get_mlkem_instance()

    # DecapsKey.from_bytes signature differs by version
    try:
        dk = DecapsKey.from_bytes(dk_bytes)
    except TypeError:
        dk = DecapsKey.from_bytes(dk_bytes, ParameterSet.ML_KEM_512)

    decaps_start = time.time()
    ss = mlkem_obj.decaps(dk, ct)  # Recover ss 32B
    decaps_ms = (time.time() - decaps_start) * 1000

    assert len(ss) == SS_LEN

    # AES-256-GCM decrypt using recovered ss
    aes_start = time.time()
    aesgcm = AESGCM(ss)
    plaintext = aesgcm.decrypt(nonce, aes_ct, None)
    aes_ms = (time.time() - aes_start) * 1000

    total_ms = (time.time() - start) * 1000
    metrics = {
        "decaps_ms": round(decaps_ms, 2),
        "aes_decrypt_ms": round(aes_ms, 2),
        "total_ms": round(total_ms, 2),
        "ct_len": len(ct),
        "total_len": len(packet),
    }

    # PQC observability: log decaps time
    logging.info(
        f"PQC decrypt: decaps {metrics['decaps_ms']}ms, AES {metrics['aes_decrypt_ms']}ms, total {len(packet)}B"
    )

    return plaintext, metrics


# Simple self-test when run directly
if __name__ == "__main__":
    print("Testing PQC utils round-trip...")
    ek_b, dk_b, mlkem_o = generate_keypair(Path("/tmp/test_pk.bin"))
    msg = b'{"device_id":"sensor-node-01","temperature":21.8}'
    pkt, enc_metrics = encrypt_for_cloud(msg, ek_b)
    print(f"Encrypted packet len {len(pkt)}, metrics {enc_metrics}")
    plain, dec_metrics = decrypt_from_gateway(pkt, dk_b, mlkem_o)
    print(f"Decrypted: {plain}, metrics {dec_metrics}")
    assert plain == msg
    print("Round-trip OK!")
