# --- Metrics (in-memory, thread-safe via lock) ---
# Simple counters for observability, exposed via health endpoint
# For gateway side metrics, see edge_gateway.py which has received/rejected/replayed/forwarded/fallback
metrics_lock = threading.Lock()
metrics = {
    "total_received": 0,  # Total TCP connections with data received on 6000
    "decaps_ok": 0,  # PQC decapsulation + AES decrypt succeeded
    "decaps_fail": 0,  # PQC decaps or AES decrypt failed (tampered, wrong key, truncated)
    "json_fail": 0,  # JSON parse failed after decrypt
    "db_rows": 0,  # Current DB row count
    "avg_decaps_ms": 0.0,  # Average decapsulation time for PQC observability
    "total_decaps_ms": 0.0,  # Sum for avg calculation
    "uptime_start": time.time(),
}

# DB lock for thread safety (health thread reads DB, main thread writes)
db_lock = threading.Lock()
db_conn = None  # Global sqlite connection


def init_db():
    """Initialize SQLite DB and create table if not exists - simple DB for cloud side"""
    global db_conn
    # Ensure parent dir exists for shared volume case (e.g., shared/telemetry.db)
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    # check_same_thread=False allows sharing connection across threads (health thread reads, main writes)
    # For production, use separate connections per thread or connection pool
    db_conn = sqlite3.connect(str(DB_PATH), check_same_thread=False)
    db_conn.execute(
        """
        CREATE TABLE IF NOT EXISTS telemetry (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            device_id TEXT,
            timestamp INTEGER,
            temperature REAL,
            humidity REAL,
            status TEXT,
            received_at INTEGER,
            source_ip TEXT,
            pqc_decaps_ms REAL,
            raw_json TEXT
        )
        """
    )
    db_conn.commit()
    # Get current count for metrics
    cursor = db_conn.execute("SELECT COUNT(*) FROM telemetry")
    count = cursor.fetchone()[0]
    with metrics_lock:
        metrics["db_rows"] = count
    logging.info(f"DB initialized at {DB_PATH}, existing rows: {count}")
    return db_conn


def insert_telemetry(
    device_id: str,
    timestamp: int,
    temperature: float,
    humidity: float,
    status: str,
    received_at: int,
    source_ip: str,
    decaps_ms: float,
    raw_json: str,
):
    """Insert telemetry row into DB - simple DB insert, no ORM"""
    with db_lock:
        db_conn.execute(
            """
            INSERT INTO telemetry 
            (device_id, timestamp, temperature, humidity, status, received_at, source_ip, pqc_decaps_ms, raw_json)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                device_id,
                timestamp,
                temperature,
                humidity,
                status,
                received_at,
                source_ip,
                decaps_ms,
                raw_json,
            ),
        )
        db_conn.commit()
        cursor = db_conn.execute("SELECT COUNT(*) FROM telemetry")
        count = cursor.fetchone()[0]
    with metrics_lock:
        metrics["db_rows"] = count
    logging.info(f"Inserted telemetry device={device_id} temp={temperature}, db_rows={count}")


def get_analytics():
    """
    Get analytics from DB + metrics - simple analytics as observability
    This is the "simple analytics work on cloud side" you asked about
    Returns dict with db_rows, total_received, analytics (avg temp/humidity, last 10), pqc metrics, uptime
    """
    with db_lock:
        try:
            # Total count and averages
            cursor = db_conn.execute(
                "SELECT COUNT(*), AVG(temperature), AVG(humidity), MAX(timestamp) FROM telemetry"
            )
            count, avg_temp, avg_hum, max_ts = cursor.fetchone()
            # Last 10 telemetry for recent view
            cursor = db_conn.execute(
                "SELECT device_id, timestamp, temperature, humidity, status, received_at FROM telemetry ORDER BY received_at DESC LIMIT 10"
            )
            last_10 = [
                {
                    "device_id": row[0],
                    "timestamp": row[1],
                    "temperature": row[2],
                    "humidity": row[3],
                    "status": row[4],
                    "received_at": row[5],
                }
                for row in cursor.fetchall()
            ]
        except Exception as e:
            logging.error(f"Analytics query failed: {e}")
            count, avg_temp, avg_hum, max_ts, last_10 = 0, 0, 0, 0, []

    with metrics_lock:
        total = metrics["decaps_ok"] + metrics["decaps_fail"]
        success_rate = metrics["decaps_ok"] / total if total > 0 else 0
        avg_decaps = metrics["avg_decaps_ms"]
        uptime = time.time() - metrics["uptime_start"]
        analytics = {
            "status": "ok",
            "db_rows": metrics["db_rows"],
            "total_received": metrics["total_received"],
            "analytics": {
                "total_count": count,
                "avg_temperature": round(avg_temp, 2) if avg_temp else 0,
                "avg_humidity": round(avg_hum, 2) if avg_hum else 0,
                "max_timestamp": max_ts,
                "last_10": last_10,
            },
            "pqc": {
                "decaps_ok": metrics["decaps_ok"],
                "decaps_fail": metrics["decaps_fail"],
                "json_fail": metrics["json_fail"],
                "success_rate": round(success_rate, 3),
                "avg_decaps_ms": round(avg_decaps, 2),
            },
            "uptime_s": round(uptime, 1),
        }
    return analytics


class HealthHandler(BaseHTTPRequestHandler):
    """Health/analytics HTTP handler for cloud (port 6001)"""

    def do_GET(self):
        # Handle /health, /analytics, / - return JSON analytics
        if self.path in ["/health", "/analytics", "/"]:
            analytics = get_analytics()
            self.send_response(200)
            self.send_header("Content-type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps(analytics, indent=2).encode())
        else:
            self.send_response(404)
            self.end_headers()
            self.wfile.write(b'{"status":"not found"}')

    def log_message(self, format, *args):
        # Log health requests to file (not stdout) to keep stdout clean
        logging.info(f"Health request {self.client_address} {format % args}")


def start_health_server():
    """Start health/analytics HTTP server on 6001 in background daemon thread"""
    server = HTTPServer((HEALTH_HOST, HEALTH_PORT), HealthHandler)
    logging.info(f"Cloud health/analytics listening on {HEALTH_HOST}:{HEALTH_PORT}")
    print(f"Cloud health/analytics listening on {HEALTH_PORT}...")
    server.serve_forever()


def start_cloud():
    """Main cloud data plane server on 6000 - handles PQC packets from gateway"""
    # Generate ML-KEM keypair on startup - this is where cloud_public_key.bin comes from
    # For local: writes to ./cloud_public_key.bin (800B)
    # For Docker: writes to /app/shared/cloud_public_key.bin if CLOUD_PK_PATH env var set to that path
    ek_bytes, dk_bytes, mlkem_obj = generate_keypair(CLOUD_PK_PATH)
    logging.info(f"Cloud PQC keypair generated, pk saved to {CLOUD_PK_PATH}")

    # Init SQLite DB - this is where telemetry.db comes from
    # For local: ./telemetry.db created in current dir
    # For Docker: /app/telemetry.db or /app/shared/telemetry.db depending on DB_PATH env var
    init_db()

    # Start health server in background thread (daemon, dies when main dies)
    health_thread = threading.Thread(target=start_health_server, daemon=True)
    health_thread.start()

    # Data plane TCP server (Link2: Gateway -> Cloud PQC)
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as server:
        server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        server.bind((CLOUD_HOST, CLOUD_PORT))
        server.listen()
        # This print is expected for manual run, not used by tests (cloud not tested via GatewayProcess)
        print(f"Cloud Service listening for gateway on port {CLOUD_PORT}...")
        logging.info(f"Cloud Service listening on {CLOUD_HOST}:{CLOUD_PORT}")

        while True:
            try:
                conn, addr = server.accept()
            except Exception as e:
                logging.error(f"Accept failed: {e}", exc_info=True)
                continue

            with conn:
                buffer = bytearray()
                try:
                    while True:
                        # Read chunks until EOF (gateway does sendall + shutdown WR)
                        chunk = conn.recv(4096)
                        if not chunk:
                            break
                        buffer.extend(chunk)
                except Exception as e:
                    logging.warning(f"Recv error from {addr}: {e}")
                    continue

                if not buffer:
                    logging.info(f"Empty connection from {addr}")
                    continue

                with metrics_lock:
                    metrics["total_received"] += 1

                # Try PQC decrypt (hybrid: decaps ct -> ss, AES-GCM decrypt)
                try:
                    plaintext, dec_metrics = decrypt_from_gateway(
                        bytes(buffer), dk_bytes, mlkem_obj
                    )
                    decaps_ms = dec_metrics["decaps_ms"]

                    # Update avg decaps ms for PQC observability
                    with metrics_lock:
                        metrics["total_decaps_ms"] += decaps_ms
                        total_ok = metrics["decaps_ok"] + 1
                        metrics["avg_decaps_ms"] = (
                            metrics["total_decaps_ms"] / total_ok
                            if total_ok > 0
                            else 0
                        )
                        metrics["decaps_ok"] += 1

                    # Parse JSON after PQC decrypt
                    try:
                        payload = json.loads(plaintext.decode("utf-8"))
                    except Exception as e:
                        logging.warning(f"JSON parse fail from {addr}: {e}")
                        with metrics_lock:
                            metrics["json_fail"] += 1
                        continue

                    # Extract fields for DB insert (with defaults for robustness)
                    device_id = payload.get("device_id", "unknown")
                    timestamp = payload.get("timestamp", int(time.time()))
                    temperature = payload.get("temperature", 0)
                    humidity = payload.get("humidity", 0)
                    status = payload.get("status", "OK")
                    received_at = int(time.time())
                    source_ip = addr[0]

                    # Insert into SQLite (simple DB)
                    insert_telemetry(
                        device_id,
                        timestamp,
                        temperature,
                        humidity,
                        status,
                        received_at,
                        source_ip,
                        decaps_ms,
                        json.dumps(payload),
                    )

                    # Print for manual verification (not used by tests)
                    print(f"Cloud received from {device_id}: {payload}")
                    logging.info(
                        f"Cloud stored telemetry from {device_id} temp={temperature} from {addr}"
                    )

                except Exception as e:
                    # PQC decaps or AES decrypt failed -> reject but keep cloud alive (no crash)
                    logging.warning(
                        f"Rejected PQC packet from {addr}: {type(e).__name__}: {e}"
                    )
                    with metrics_lock:
                        metrics["decaps_fail"] += 1
                    continue


if __name__ == "__main__":
    start_cloud()
